// Translation workflow for page content (matchup notes, reverse notes, map
// texts) in Spanish and Brazilian Portuguese. See scripts/lib/content-i18n.mjs
// for the key scheme.
//
//   node scripts/i18n-content.mjs status
//       Counts of current / missing / stale translations per language.
//   node scripts/i18n-content.mjs extract <dir>
//       Writes every missing or stale English sentence to
//       <dir>/<lang>/src/<chunk>.json ({ protected, strings }), ~25k chars each.
//       Translate each chunk into <dir>/<lang>/out/<chunk>.json (same keys,
//       translated values), following scripts/i18n/guide-<lang>.md.
//   node scripts/i18n-content.mjs check <dir> <lang> <chunk>
//       Validates one translated chunk (keys, protected names, length).
//   node scripts/i18n-content.mjs merge <dir>
//       Validates every translated chunk, merges it into docs/i18n/<lang>/,
//       drops translations whose English is gone, and records source hashes.
//
// After merging: npm run generate:maps && npm run generate && npm test.

import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync } from "node:fs";
import { join } from "node:path";

import { matchupNotes } from "../docs/matchup-notes.js";
import { reverseNotes } from "../docs/reverse-notes.js";
import { maps } from "../docs/map-data.js";
import {
  CONTENT_LANGS, hash8, englishEntries, protectedNames, mentions,
  contentPaths, contentStatus,
} from "./lib/content-i18n.mjs";

const CHUNK_CHARS = 25000;
const [cmd, dir, ...rest] = process.argv.slice(2);

function readJson(file) {
  return JSON.parse(readFileSync(file, "utf8"));
}

// Problems with one translated chunk, or [] when it is good to merge.
export function checkChunk(src, out) {
  const errors = [];
  for (const k of Object.keys(src.strings)) if (!(k in out)) errors.push(`missing key: ${k}`);
  for (const k of Object.keys(out)) if (!(k in src.strings)) errors.push(`unexpected key: ${k}`);
  for (const [k, en] of Object.entries(src.strings)) {
    const t = out[k];
    if (!(k in out)) continue;
    if (typeof t !== "string" || !t.trim()) { errors.push(`empty: ${k}`); continue; }
    if (t.trim() === en.trim()) errors.push(`untranslated: ${k}`);
    const ratio = t.length / en.length;
    if (ratio < 0.6 || ratio > 2.2) errors.push(`length ratio ${ratio.toFixed(2)}: ${k}`);
    for (const name of src.protected) {
      if (mentions(en, name) && !t.includes(name)) errors.push(`name "${name}" must appear verbatim: ${k}`);
    }
  }
  return errors;
}

async function status() {
  for (const lang of CONTENT_LANGS) {
    const { status: st, orphans } = await contentStatus(lang);
    const count = s => [...st.values()].filter(v => v === s).length;
    console.log(`${lang}: ${count("ok")} current, ${count("missing")} missing, ${count("stale")} stale, ${orphans.length} orphaned`);
  }
}

async function extract() {
  if (!dir) throw new Error("usage: extract <dir>");
  for (const lang of CONTENT_LANGS) {
    const { en, status: st } = await contentStatus(lang);
    const todo = [...en].filter(([k]) => st.get(k) !== "ok");
    const srcDir = join(dir, lang, "src");
    mkdirSync(srcDir, { recursive: true });
    mkdirSync(join(dir, lang, "out"), { recursive: true });
    let chunk = [], size = 0, n = 0;
    const flush = () => {
      if (!chunk.length) return;
      const text = chunk.map(e => e[1]).join("\n");
      const id = `chunk-${String(++n).padStart(2, "0")}`;
      writeFileSync(join(srcDir, `${id}.json`), JSON.stringify({
        protected: protectedNames.filter(nm => mentions(text, nm)),
        strings: Object.fromEntries(chunk),
      }, null, 1));
      chunk = []; size = 0;
    };
    for (const e of todo) {
      chunk.push(e); size += e[1].length;
      if (size >= CHUNK_CHARS) flush();
    }
    flush();
    console.log(`${lang}: ${todo.length} sentence(s) to translate in ${n} chunk(s) under ${srcDir}`);
  }
}

function check() {
  const [lang, id] = rest;
  if (!dir || !lang || !id) throw new Error("usage: check <dir> <lang> <chunk>");
  const src = readJson(join(dir, lang, "src", `${id}.json`));
  let out;
  try { out = readJson(join(dir, lang, "out", `${id}.json`)); }
  catch (e) { console.log(`FAIL ${lang}/${id}: cannot read/parse output: ${e.message}`); process.exit(1); }
  const errors = checkChunk(src, out);
  if (errors.length) {
    console.log(`FAIL ${lang}/${id}: ${errors.length} problem(s)\n${errors.slice(0, 60).join("\n")}`);
    process.exit(1);
  }
  console.log(`OK ${lang}/${id}: ${Object.keys(out).length} strings`);
}

function moduleSource(exportName, value, sourceFile) {
  return `// ${sourceFile} translated; same keys and nesting as the English file.
// GENERATED by scripts/i18n-content.mjs merge — hand-edits are fine, but keep
// brawler, gadget, star power, map and mode names exactly as in English.

export const ${exportName} = ${JSON.stringify(value, null, 2)};
`;
}

async function merge() {
  if (!dir) throw new Error("usage: merge <dir>");
  const en = englishEntries();
  for (const lang of CONTENT_LANGS) {
    const outDir = join(dir, lang, "out");
    if (!existsSync(outDir)) continue;
    const { entries, sources } = await contentStatus(lang);
    const merged = new Map(entries);
    const hashes = { ...sources };
    let added = 0;
    for (const file of readdirSync(outDir).filter(f => f.endsWith(".json")).sort()) {
      const id = file.replace(/\.json$/, "");
      const src = readJson(join(dir, lang, "src", file));
      const out = readJson(join(outDir, file));
      const errors = checkChunk(src, out);
      if (errors.length) throw new Error(`${lang}/${id} failed validation:\n${errors.slice(0, 20).join("\n")}`);
      for (const [k, t] of Object.entries(out)) {
        if (en.get(k) !== src.strings[k]) continue; // English moved on since extract
        merged.set(k, t.trim());
        hashes[k] = hash8(src.strings[k]);
        added++;
      }
    }

    // Rebuild the nested modules in English order; translations whose English
    // no longer exists are dropped.
    const tm = {}, tr = {}, mt = {};
    const put = (obj, a, b, v) => { (obj[a] ??= {})[b] = v; };
    for (const [d, o] of Object.entries(matchupNotes)) for (const c of Object.keys(o)) {
      const v = merged.get(`m|${d}|${c}`); if (v) put(tm, d, c, v);
    }
    for (const [d, o] of Object.entries(reverseNotes)) for (const c of Object.keys(o)) {
      const v = merged.get(`r|${d}|${c}`); if (v) put(tr, d, c, v);
    }
    for (const m of maps) {
      const entry = {};
      const s = merged.get(`s|${m.slug}`); if (s) entry.summary = s;
      for (const tier of Object.values(m.picks)) for (const p of tier) {
        const v = typeof p === "object" && merged.get(`p|${m.slug}|${p.name}`);
        if (v) (entry.picks ??= {})[p.name] = v;
      }
      for (const b of m.bans ?? []) {
        const v = merged.get(`b|${m.slug}|${b.name}`);
        if (v) (entry.bans ??= {})[b.name] = v;
      }
      if (Object.keys(entry).length) mt[m.slug] = entry;
    }
    const keep = Object.fromEntries(Object.entries(hashes).filter(([k]) => en.has(k) && merged.has(k)).sort());

    const p = contentPaths(lang);
    mkdirSync(p.dir, { recursive: true });
    mkdirSync(join(p.sources, ".."), { recursive: true });
    writeFileSync(p.matchup, moduleSource("matchupNotes", tm, "docs/matchup-notes.js"));
    writeFileSync(p.reverse, moduleSource("reverseNotes", tr, "docs/reverse-notes.js"));
    writeFileSync(p.maps, moduleSource("mapText", mt, "docs/map-data.js (summary, S-tier and ban whys)"));
    writeFileSync(p.sources, JSON.stringify(keep, null, 1) + "\n");
    console.log(`${lang}: merged ${added} sentence(s); ${Object.keys(keep).length} current translations recorded`);
  }
  await status();
}

const commands = { status, extract, check, merge };
if (!commands[cmd]) {
  console.log("usage: node scripts/i18n-content.mjs status | extract <dir> | check <dir> <lang> <chunk> | merge <dir>");
  process.exit(1);
}
await commands[cmd]();
